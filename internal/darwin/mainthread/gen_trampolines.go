//go:build ignore

// gen_trampolines writes the tables of the trampolines of the worker,
// trampolines_darwin_arm64.s and trampolines_darwin_amd64.s: entry i loads
// i into a scratch register and branches to trampolineCommon, and lies
// stride bytes per entry past the start of the table, as
// trampolineAddress counts.
package main

import (
	"bytes"
	"fmt"
	"os"
)

const trampolines = 2048

func main() {
	for _, a := range []struct {
		arch, entry string
	}{
		// Two instructions of four bytes.
		{"arm64", "\tMOVD\t$%d, R16\n\tJMP\t·trampolineCommon(SB)\n"},
		// Each entry starts at a multiple of 16 bytes and takes at most
		// 11: a MOVL of 6 bytes and a JMP of 5.
		{"amd64", "\tPCALIGN\t$16\n\tMOVL\t$%d, R11\n\tJMP\t·trampolineCommon(SB)\n"},
	} {
		var b bytes.Buffer
		b.WriteString("// Code generated by gen_trampolines.go; DO NOT EDIT.\n\n")
		fmt.Fprintf(&b, "//go:build darwin && %s\n\n#include \"textflag.h\"\n\n", a.arch)
		b.WriteString("// trampolineTable holds the trampolines of the worker.\n")
		b.WriteString("TEXT ·trampolineTable(SB), NOSPLIT|NOFRAME, $0-0\n")
		for i := range trampolines {
			fmt.Fprintf(&b, a.entry, i)
		}
		name := "trampolines_darwin_" + a.arch + ".s"
		if err := os.WriteFile(name, b.Bytes(), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}
